#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md from Cargo.lock and app/package-lock.json.
// `--check` fails when the file is stale, when a package has no license, and when a
// copyleft license isn't listed in ALLOWED_COPYLEFT (used by check.sh).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'THIRD_PARTY_LICENSES.md');
const checkOnly = process.argv.includes('--check');

// Each entry needs a matching entry in docs/DECISIONS.md, as CLAUDE.md asks: `name` -> reason.
const ALLOWED_COPYLEFT = {};

const byName = (a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name < b.name ? -1 : 1);

function rustPackages() {
  const json = execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 1 << 28,
  });
  return JSON.parse(json)
    .packages.filter((p) => p.source !== null)
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? '' }));
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, 'app/package-lock.json'), 'utf8'));
  return Object.entries(lock.packages)
    // an optional peer isn't installed, and npm versions disagree on listing it
    .filter(([path, p]) => path !== '' && !(p.optional && p.peer))
    .map(([path, p]) => ({
      name: path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length),
      version: p.version,
      license: p.license ?? '',
    }));
}

const unique = (list) => [...new Map(list.map((p) => [`${p.name}@${p.version}`, p])).values()].sort(byName);

function table(list) {
  const rows = list.map((p) => `| ${p.name} | ${p.version} | ${p.license.replaceAll('|', '\\|')} |`);
  return ['| Package | Version | License |', '|---|---|---|', ...rows].join('\n');
}

const rust = unique(rustPackages());
const npm = unique(npmPackages());
const text = `# Third-party licenses

Generated by \`scripts/licenses.mjs\` from \`Cargo.lock\` and \`app/package-lock.json\`. Do not edit it. To update it, run \`node scripts/licenses.mjs\`.

## Rust crates (${rust.length})

${table(rust)}

## npm packages (${npm.length})

${table(npm)}
`;

const problems = [];
for (const p of [...rust, ...npm]) {
  if (!p.license) problems.push(`${p.name} ${p.version}: no license in the lockfile or crate metadata`);
  else if (/\b(A?GPL|LGPL)/i.test(p.license) && !/\bOR\b|\//i.test(p.license) && !(p.name in ALLOWED_COPYLEFT)) {
    problems.push(`${p.name} ${p.version}: ${p.license} needs a DECISIONS.md entry and ALLOWED_COPYLEFT`);
  }
}

if (checkOnly) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replaceAll('\r\n', '\n') : '';
  if (current !== text) problems.push('THIRD_PARTY_LICENSES.md is stale. Run: node scripts/licenses.mjs');
} else {
  writeFileSync(out, text);
}

if (problems.length) {
  console.error(`licenses:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log(`licenses: ${rust.length} crates, ${npm.length} npm packages${checkOnly ? ', in sync' : ', written'}`);
